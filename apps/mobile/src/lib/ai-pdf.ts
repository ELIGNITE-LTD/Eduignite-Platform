/**
 * An answer, saved as a document someone can keep.
 *
 * A student who asks a good question gets a good explanation and then loses it
 * the next time they clear the app. This turns one exchange into a PDF with
 * the question at the top and the whole answer under it, headed like every
 * other EduIgnite document.
 *
 * The answer is captured from what is already on screen rather than rebuilt
 * from the markdown. That matters: the mathematics has been typeset by KaTeX,
 * the charts drawn by the charting library, the tables laid out by the
 * browser. Redrawing all of that a second time in PDF primitives would mean a
 * second implementation that drifts from the first. Photographing the finished
 * article keeps the page and the document identical by construction.
 *
 * This file is identical in the website, mobile and desktop apps.
 */

const A4 = { width: 210, height: 297 };
const MARGIN = 14;
const HEADER = 30;
const FOOTER = 12;
const NAVY = { r: 18, g: 49, b: 77 };

function stamp(): string {
  return new Date().toLocaleString(undefined, {
    day: "2-digit",
    month: "short",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  });
}

/** A filename that says what it is and sorts by date. */
function fileName(question: string): string {
  const slug = question
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 48);
  const date = new Date().toISOString().slice(0, 10);
  return `eduignite-answer-${slug || "question"}-${date}.pdf`;
}

export type AnswerPdfInput = {
  /** The rendered answer, exactly as the reader sees it. */
  node: HTMLElement;
  question: string;
  askedBy?: string;
  schoolName?: string;
};

/**
 * Write the PDF and hand it to the browser.
 *
 * Returns the filename so the caller can say what was saved. Throws if the
 * page could not be captured, which the caller reports rather than swallows.
 */
export async function downloadAnswerPdf({
  node,
  question,
  askedBy,
  schoolName,
}: AnswerPdfInput): Promise<string> {
  const [{ default: jsPDF }, { default: html2canvas }] = await Promise.all([
    import("jspdf"),
    import("html2canvas"),
  ]);

  // Capture at twice the size so the text is still sharp on paper.
  const canvas = await html2canvas(node, {
    scale: 2,
    backgroundColor: "#ffffff",
    logging: false,
    useCORS: true,
    // The answer may be taller than its scroll box; capture all of it.
    windowWidth: node.scrollWidth,
    height: node.scrollHeight,
  });

  const pdf = new jsPDF({ unit: "mm", format: "a4", orientation: "portrait" });
  const usableWidth = A4.width - MARGIN * 2;
  const usableHeight = A4.height - HEADER - FOOTER - MARGIN;

  const drawFurniture = (pageNumber: number, pageCount: number) => {
    pdf.setFillColor(NAVY.r, NAVY.g, NAVY.b);
    pdf.rect(0, 0, A4.width, 20, "F");

    pdf.setTextColor(255, 255, 255);
    pdf.setFont("helvetica", "bold");
    pdf.setFontSize(13);
    pdf.text("EduIgnite", MARGIN, 9);

    pdf.setFont("helvetica", "normal");
    pdf.setFontSize(8);
    pdf.text(schoolName || "AI Assistant", MARGIN, 15);
    pdf.text(stamp(), A4.width - MARGIN, 15, { align: "right" });

    pdf.setTextColor(120, 130, 145);
    pdf.setFontSize(8);
    pdf.text(
      `Generated by the EduIgnite AI Assistant${askedBy ? ` for ${askedBy}` : ""}`,
      MARGIN,
      A4.height - 8,
    );
    pdf.text(`Page ${pageNumber} of ${pageCount}`, A4.width - MARGIN, A4.height - 8, {
      align: "right",
    });
  };

  // ---- The question, wrapped, on the first page ----
  pdf.setFont("helvetica", "bold");
  pdf.setFontSize(9);
  pdf.setTextColor(NAVY.r, NAVY.g, NAVY.b);
  const questionLines = pdf.splitTextToSize(question.trim() || "Question", usableWidth - 8);
  const questionHeight = Math.max(16, questionLines.length * 4.6 + 11);

  const imageWidth = usableWidth;
  const imageHeight = (canvas.height * imageWidth) / canvas.width;

  // How much of the answer fits on the first page, once the question has had
  // its room, and how much fits on each page after that.
  const firstPageRoom = usableHeight - questionHeight - 4;
  const laterPageRoom = usableHeight;
  const pageCount =
    imageHeight <= firstPageRoom
      ? 1
      : 1 + Math.ceil((imageHeight - firstPageRoom) / laterPageRoom);

  drawFurniture(1, pageCount);

  let y = HEADER - 6;
  pdf.setDrawColor(226, 232, 240);
  pdf.setFillColor(246, 249, 252);
  pdf.roundedRect(MARGIN, y, usableWidth, questionHeight, 3, 3, "FD");
  pdf.setFont("helvetica", "bold");
  pdf.setFontSize(7.5);
  pdf.setTextColor(103, 208, 228);
  pdf.text("QUESTION", MARGIN + 4, y + 6);
  pdf.setFontSize(9);
  pdf.setTextColor(NAVY.r, NAVY.g, NAVY.b);
  pdf.text(questionLines, MARGIN + 4, y + 12);
  y += questionHeight + 4;

  // ---- The answer, sliced across as many pages as it needs ----
  const image = canvas.toDataURL("image/png");
  const pixelsPerMm = canvas.height / imageHeight;

  let consumed = 0;
  let page = 1;
  let room = firstPageRoom;

  while (consumed < imageHeight - 0.5) {
    const sliceHeight = Math.min(room, imageHeight - consumed);

    // Draw the whole image, clipped to the slice that belongs on this page.
    // jsPDF has no image cropping, so the picture is offset upward and the
    // page's clip does the rest.
    const slice = document.createElement("canvas");
    slice.width = canvas.width;
    slice.height = Math.round(sliceHeight * pixelsPerMm);
    const context = slice.getContext("2d");
    if (!context) throw new Error("This browser could not prepare the document.");
    context.fillStyle = "#ffffff";
    context.fillRect(0, 0, slice.width, slice.height);
    context.drawImage(canvas, 0, Math.round(consumed * pixelsPerMm), canvas.width, slice.height, 0, 0, canvas.width, slice.height);

    pdf.addImage(slice.toDataURL("image/png"), "PNG", MARGIN, y, imageWidth, sliceHeight, undefined, "FAST");

    consumed += sliceHeight;
    if (consumed < imageHeight - 0.5) {
      pdf.addPage();
      page += 1;
      drawFurniture(page, pageCount);
      y = HEADER - 6;
      room = laterPageRoom;
    }
  }

  // `image` is kept only so the capture is not garbage collected mid-write on
  // slower devices; jsPDF has already copied what it needs.
  void image;

  const name = fileName(question);
  pdf.save(name);
  return name;
}
