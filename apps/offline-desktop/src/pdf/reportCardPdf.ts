import type { TDocumentDefinitions } from 'pdfmake/interfaces';
import type { ReportCard, School, Student } from '../shared/types';
import type { SubjectResult } from '../domain/grading';

import {
  OFFICIAL,
  officialHeader,
  officialSignature,
  officialStyles,
  officialTableLayout,
} from './officialHeader';

export interface ReportCardPdfInput {
  school: School;
  student: Student;
  reportCard: ReportCard;
  subjects: SubjectResult[];
}

const fmt = (n: number | null) => (n === null ? '—' : n.toFixed(2));

/** A4 with 40pt side margins leaves 515pt between them. */
const CONTENT_WIDTH = 515;

export function buildReportCardDocDefinition(input: ReportCardPdfInput): TDocumentDefinitions {
  const { school, student, reportCard, subjects } = input;

  const fact = (label: string, value: string) => ({
    text: [
      { text: `${label}: `, color: OFFICIAL.muted },
      { text: value, bold: true, color: OFFICIAL.ink },
    ],
    fontSize: 9.5,
    margin: [0, 2, 0, 2] as [number, number, number, number],
  });

  return {
    pageSize: 'A4',
    pageMargins: [40, 36, 40, 50],
    footer: (page: number, pages: number) => ({
      columns: [
        { text: `Generated by EduIgnite Offline  |  ${reportCard.generated_at}`, style: 'muted' },
        { text: `Page ${page} of ${pages}`, style: 'muted', alignment: 'right' },
      ],
      margin: [40, 16, 40, 0],
    }),
    content: [
      ...officialHeader({
        schoolName: school.name,
        motto: school.motto,
        title: `Official ${reportCard.term} Report Card`,
        chips: [
          { label: 'Academic Year', value: reportCard.academic_year },
          { label: 'Class Rank', value: `${reportCard.class_rank ?? '—'} of ${reportCard.class_size ?? '—'}` },
        ],
        contentWidth: CONTENT_WIDTH,
      }),
      {
        columns: [
          { width: '*', stack: [fact('Student', `${student.first_name} ${student.last_name}`)] },
          { width: 'auto', stack: [fact('Admission No', student.admission_number)] },
        ],
        margin: [0, 0, 0, 8],
      },
      {
        table: {
          headerRows: 1,
          widths: ['*', 'auto', 'auto', 'auto', 'auto'],
          body: [
            [
              { text: 'SUBJECT', style: 'tableHeader' },
              { text: 'COEF', style: 'tableHeader', alignment: 'center' },
              { text: 'CAT AVG', style: 'tableHeader', alignment: 'center' },
              { text: 'EXAM', style: 'tableHeader', alignment: 'center' },
              { text: 'WEIGHTED', style: 'tableHeader', alignment: 'center' },
            ],
            ...subjects.map((s) => [
              { text: s.subjectName, color: OFFICIAL.ink },
              { text: String(s.coefficient), alignment: 'center' as const },
              { text: fmt(s.catAverage), alignment: 'center' as const },
              { text: fmt(s.examScore), alignment: 'center' as const },
              { text: fmt(s.weightedScore), alignment: 'center' as const, bold: true },
            ]),
          ],
        },
        layout: officialTableLayout,
      },
      {
        margin: [0, 14, 0, 0],
        columns: [
          {
            width: '*',
            stack: [
              fact('Total', `${reportCard.total_score.toFixed(2)} / ${(reportCard.total_coefficient * 20).toFixed(2)}`),
              fact('Average', `${reportCard.average_score.toFixed(2)} / 20  (${reportCard.grade_range})`),
            ],
          },
          {
            width: 'auto',
            stack: [
              fact('Class Rank', `${reportCard.class_rank ?? '—'} of ${reportCard.class_size ?? '—'}`),
              fact('Promotion', reportCard.promotional_eligible ? 'Eligible for promotion' : 'Not yet eligible'),
            ],
          },
        ],
      },
      officialSignature({
        office: 'Registry & Examination Office',
        principal: school.principal,
        contentWidth: CONTENT_WIDTH,
      }),
    ],
    styles: officialStyles,
  };
}
