import type { TDocumentDefinitions } from 'pdfmake/interfaces';
import type { Payment, School, Student } from '../shared/types';

import { OFFICIAL, officialHeader, officialSignature, officialStyles } from './officialHeader';

export interface ReceiptPdfInput {
  school: School;
  student: Student;
  payment: Payment;
}

/** A5 with 30pt side margins leaves 360pt between them. */
const CONTENT_WIDTH = 360;

export function buildReceiptDocDefinition(input: ReceiptPdfInput): TDocumentDefinitions {
  const { school, student, payment } = input;

  const row = (label: string, value: string, strong = false) => [
    { text: label, color: OFFICIAL.muted, fontSize: 9 },
    { text: value, color: OFFICIAL.ink, bold: strong, fontSize: strong ? 10.5 : 9.5 },
  ];

  return {
    pageSize: 'A5',
    pageMargins: [30, 28, 30, 40],
    footer: () => ({
      text: 'Generated by EduIgnite Offline  |  Fees once paid are not refundable.',
      style: 'muted',
      alignment: 'center',
      margin: [30, 14, 30, 0],
    }),
    content: [
      ...officialHeader({
        schoolName: school.name,
        motto: school.motto,
        title: 'Official Payment Receipt',
        chips: [
          { label: 'Receipt No', value: payment.receipt_number },
          { label: 'Academic Year', value: school.academic_year },
        ],
        compact: true,
        contentWidth: CONTENT_WIDTH,
      }),
      {
        table: {
          widths: [110, '*'],
          body: [
            row('Student', `${student.first_name} ${student.last_name}`, true),
            row('Admission No', student.admission_number),
            row('Amount paid', `${payment.amount.toFixed(2)} ${payment.currency}`, true),
            row('Payment method', payment.payment_method),
            row('Reference', payment.reference_number || '—'),
            row('Date', payment.payment_date),
            row('Notes', payment.notes || '—'),
          ],
        },
        layout: {
          hLineWidth: (i: number, node: { table: { body: unknown[] } }) =>
            i === 0 || i === node.table.body.length ? 0 : 0.5,
          vLineWidth: () => 0,
          hLineColor: () => OFFICIAL.line,
          paddingTop: () => 4,
          paddingBottom: () => 4,
          fillColor: (rowIndex: number) => (rowIndex % 2 === 0 ? OFFICIAL.soft : null),
        },
      },
      officialSignature({
        office: 'Bursary Office',
        principal: school.principal,
        compact: true,
        contentWidth: CONTENT_WIDTH,
      }),
    ],
    styles: officialStyles,
  };
}
