/**
 * Basic Education report cards (Cameroon nursery and primary schools).
 *
 * Two HTML layouts, selected from the report-card payload's `layout`:
 *  - "primary": marks table (Test, Exam, Average, Coef, Coef x Avg, Class avg, Position, grade label),
 *    totals, term average, rank, attendance, conduct, remarks, annual summary + promotion, signatures.
 *  - "nursery": developmental areas x rating-scale circles, attendance, observations, head remark and
 *    a "ready for the next class" outcome. No marks, averages or ranks.
 *
 * Like every other report card in the app the output is an HTML string (rendered on screen and
 * captured to PDF by browser-download.ts), so there is no extra PDF engine. The root element
 * carries the `rc` class that the PDF capture looks for.
 */
import { resolveMediaUrl } from "@/lib/media";
import type { BasicReportCardPayload, BasicReportLayout } from "@/lib/api/types";

export type BasicReportLanguage = "en" | "fr";
export type BasicReportPaper = "A4" | "A5";

export interface BasicReportCardOptions {
  title?: string;
  school?: Record<string, any> | null;
  student?: Record<string, any> | null;
  attendance?: Record<string, any> | null;
  qrCode?: string | null;
  /** Document language. Falls back to the payload, then the school sub-system, then English. */
  language?: BasicReportLanguage;
  /** "A5" is the same design at 70.7 %. Defaults to A4. */
  paper?: BasicReportPaper;
  /** Hex accent colour (e.g. the school's brand colour). Falls back to the payload branding, then EduIgnite navy. */
  accentColor?: string | null;
}

export function isBasicReportLayout(layout: unknown): layout is Extract<BasicReportLayout, "primary" | "nursery"> {
  return layout === "primary" || layout === "nursery";
}

