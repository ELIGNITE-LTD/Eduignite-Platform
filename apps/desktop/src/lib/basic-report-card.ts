function buildNursery(m: Model): string {
  const L = m.L;
  const scale = m.scale.length ? m.scale : [];
  const levelW = scale.length ? Math.min(7, 40 / scale.length) : 7;

  const head = `<tr><th class="l">${esc(L.areas)}</th>${scale
    .map((s) => `<th style="width:${levelW}em">${esc(s.label)}</th>`)
    .join("")}</tr>`;
  const rows = m.areas.length
    ? m.areas
        .map((a) => {
          const dots = scale.map((s) => `<td><span class="dot${a.level === s.level ? " on" : ""}"></span></td>`).join("");
          const na = a.level === null ? `<span class="na" style="margin-left:.8em">${esc(L.notAssessed)}</span>` : "";
          return `<tr><td class="l">${esc(a.name)}${na}</td>${dots}</tr>`;
        })
        .join("")
    : `<tr><td class="empty l" colspan="${1 + scale.length}">${esc(L.noAreas)}</td></tr>`;

  let attendance = "";
  if (m.show.attendance) {
    const a = m.attendance;
    const cells: Array<[string, string]> = [
      [L.absences, `${a.absent}${a.excused ? ` (${L.excused}: ${a.excused})` : ""}`],
      [L.late, String(a.late)],
    ];
    if (m.show.conduct) cells.push([L.conduct, m.conduct || "-"]);
    attendance = `
      <div class="card att" style="margin-bottom:.9em">
        <h5>${esc(L.attendance)}</h5>
        ${cells.map(([k, v]) => `<div class="c"><small>${esc(k)}</small><b>${esc(v)}</b></div>`).join("")}
      </div>`;
  } else if (m.show.conduct) {
    attendance = `<div class="card att" style="margin-bottom:.9em"><h5>${esc(L.conduct)}</h5><div class="c"><b>${esc(m.conduct || "-")}</b></div></div>`;
  }

  let outcome = "";
  if (m.show.promotion && m.decision) {
    const ready = m.decision === "promoted";
    const label = m.decision === "pending" ? L.pending : ready ? L.readyNext : L.stayNursery;
    const cls = m.decision === "pending" ? "mu" : ready ? "ok" : "ko";
    outcome = `<div class="outcome"><small>${esc(L.decision)}</small><span class="pill ${cls}">${esc(label)}</span></div>`;
  }

  return `${styles(m, false)}
    <section class="rc bx bx-nursery" data-layout="nursery">
      ${header(m, L.nurseryTitle, L.nurserySub)}
      ${chips(m)}
      ${pupilBlock(m, [L.term, m.termName], false)}
      <table class="n"><thead>${head}</thead><tbody>${rows}</tbody></table>
      ${attendance}
      ${remarks(m, L.observations)}
      ${outcome}
      ${signatures(m)}
      ${footer(m)}
    </section>`;
}

