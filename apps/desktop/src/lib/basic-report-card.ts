/* ----------------------------------------------------------------------------------------------
 * Helpers
 * -------------------------------------------------------------------------------------------- */

const DEFAULT_ACCENT = "#173a5b"; // EduIgnite navy, same as the secondary report card

function esc(value: unknown): string {
  return `${value ?? ""}`
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function clean(value: unknown, fallback = ""): string {
  const text = `${value ?? ""}`.trim();
  return text || fallback;
}

function num(value: unknown): number | null {
  if (value === null || value === undefined || value === "") return null;
  const parsed = Number(value);
  return Number.isFinite(parsed) ? parsed : null;
}

function fmt(value: number | null, digits = 2): string {
  if (value === null) return "-";
  if (Number.isInteger(value)) return String(value);
  return value.toFixed(digits).replace(/0+$/, "").replace(/\.$/, "");
}

function fmt2(value: number | null): string {
  return value === null ? "-" : value.toFixed(2);
}

function ordinal(n: number, lang: BasicReportLanguage): string {
  if (lang === "fr") return n === 1 ? "1er" : `${n}e`;
  const s = ["th", "st", "nd", "rd"];
  const v = n % 100;
  return `${n}${s[(v - 20) % 10] || s[v] || s[0]}`;
}

function initials(name: string): string {
  const parts = clean(name).split(/\s+/).filter(Boolean);
  if (!parts.length) return "?";
  const letters = parts.length === 1 ? parts[0].slice(0, 2) : parts[0][0] + parts[parts.length - 1][0];
  return letters.toUpperCase();
}

function formatDob(value: unknown, lang: BasicReportLanguage): string {
  const text = clean(value);
  if (!text) return "";
  const d = new Date(`${text.slice(0, 10)}T12:00:00Z`);
  if (Number.isNaN(d.getTime())) return text;
  return d.toLocaleDateString(lang === "fr" ? "fr-FR" : "en-GB", {
    day: "numeric",
    month: "long",
    year: "numeric",
    timeZone: "UTC",
  });
}

function isHex(value: unknown): value is string {
  return typeof value === "string" && /^#[0-9a-fA-F]{6}$/.test(value.trim());
}

function mixHex(hex: string, to: [number, number, number], t: number): string {
  const h = hex.slice(1);
  const c = [parseInt(h.slice(0, 2), 16), parseInt(h.slice(2, 4), 16), parseInt(h.slice(4, 6), 16)];
  const out = c.map((v, i) => Math.round(v + (to[i] - v) * t));
  return `#${out.map((v) => v.toString(16).padStart(2, "0")).join("")}`;
}

function buildTheme(hex: string) {
  return {
    accent: hex,
    dark: mixHex(hex, [0, 0, 0], 0.22),
    soft: mixHex(hex, [255, 255, 255], 0.86),
    cream: mixHex(hex, [255, 255, 255], 0.95),
  };
}

function flag(value: unknown, fallback = true): boolean {
  return typeof value === "boolean" ? value : fallback;
}

function termLabel(L: Labels, term: unknown): string {
  const n = Number(term);
  if (n === 1) return L.firstTerm;
  if (n === 2) return L.secondTerm;
  if (n === 3) return L.thirdTerm;
  return n ? `${L.term} ${n}` : "";
}

function resolveLanguage(report: BasicReportCardPayload, options: BasicReportCardOptions, school: Record<string, any>): BasicReportLanguage {
  const candidate = clean(options.language || (report as any).branding?.language || (report as any).language || school.document_language || school.language).toLowerCase();
  if (candidate.startsWith("fr")) return "fr";
  if (candidate.startsWith("en")) return "en";
  const sub = clean(school.subsystem).toLowerCase();
  return sub === "francophone" ? "fr" : "en";
}

/* ----------------------------------------------------------------------------------------------
 * Normalisation
 * -------------------------------------------------------------------------------------------- */

interface EvalColumn {
  index: number;
  label: string;
}

interface SubjectRow {
  name: string;
  evals: Array<number | null>;
  average: number | null;
  coef: number | null;
  coefAverage: number | null;
  classAverage: number | null;
  position: number | null;
  label: string;
}

function normalise(report: BasicReportCardPayload, options: BasicReportCardOptions) {
  const rawStudent: Record<string, any> = { ...(report.student || {}) };
  const optStudent = options.student || {};
  // Only fill gaps from the caller's student record; the payload wins.
  const student: Record<string, any> = { ...optStudent, ...rawStudent };
  for (const key of ["photo", "avatar", "matricule"]) {
    if (!clean(rawStudent[key]) && clean(optStudent[key])) student[key] = optStudent[key];
  }
  const school: Record<string, any> = { ...(student.school || {}), ...(report.school || {}), ...(options.school || {}) };
  const lang = resolveLanguage(report, options, school);
  const L = LABELS[lang];

  const assessment: Record<string, any> = (report.assessment as any) || {};
  const maxScore = num(assessment.max_score) ?? num(report.max_score) ?? 20;
  const passMark = num(assessment.pass_mark) ?? num(report.pass_mark) ?? maxScore / 2;
  const showAverage = flag(assessment.show_average, flag(report.show_average));
  const showCoefficients = flag(report.show_coefficients, flag(assessment.show_coefficients)) && flag(report.use_coefficients, flag(assessment.use_coefficients));

  const brandingColor = clean(
    (report as any).branding?.accent_color || (report as any).branding?.primary_color || (report as any).branding?.color,
  );
  const accent = [options.accentColor, brandingColor, school.primary_color, school.brand_color].find(isHex) || DEFAULT_ACCENT;

  const termNumber = num(report.term_number) ?? num(report.sequence?.term);
  const academicYear = clean(report.academic_year || report.sequence?.academic_year || school.academic_year).replace(/-/g, "/");

  const evalLabels: Array<{ label?: string; label_fr?: string }> = Array.isArray(assessment.evaluation_labels) ? assessment.evaluation_labels : [];

  const gradeRows: any[] = Array.isArray(report.grades) ? report.grades : [];
  const evalCount = gradeRows.reduce((m, r) => Math.max(m, Array.isArray(r?.sequence_scores) ? r.sequence_scores.length : 0), 0);
  const evalColumns: EvalColumn[] = showAverage
    ? Array.from({ length: Math.min(evalCount, 3) }, (_, i) => {
        const configured = evalLabels[i];
        const sample = gradeRows.map((r) => r?.sequence_scores?.[i]).find(Boolean);
        const fallback = i === 0 ? L.test : i === 1 ? L.exam : `${L.exam} ${i}`;
        const label =
          lang === "fr"
            ? clean(configured?.label_fr || sample?.evaluation_label_fr)
            : clean(configured?.label || sample?.evaluation_label);
        return { index: i, label: (label || fallback).toUpperCase() };
      })
    : [];

  const rows: SubjectRow[] = gradeRows.map((row) => {
    const seq: any[] = Array.isArray(row?.sequence_scores) ? row.sequence_scores : [];
    const average = showAverage ? num(row.average) ?? num(row.score) : null;
    const coef = num(row.coefficient);
    const labelFr = clean(row.grade_label_fr);
    const labelEn = clean(row.grade_label || row.grade_letter);
    let label = lang === "fr" ? labelFr || labelEn : labelEn;
    const remark = clean(row.remark);
    if (label && label.length <= 2 && remark && lang === "en") label = `${label} - ${remark}`;
    return {
      name: clean(row.subject_name || row.name, "-"),
      evals: evalColumns.map((c) => num(seq[c.index]?.score)),
      average,
      coef,
      coefAverage: showAverage ? num(row.total) ?? (average !== null && coef !== null ? average * coef : null) : null,
      classAverage: num(row.class_average),
      position: num(row.position),
      label,
    };
  });

  const termAverages = (report.term_averages || {}) as Record<string, number | null>;
  const hasAnnual = termNumber === 3 && (Object.keys(termAverages).length > 0 || report.annual_average != null);

  const attendance: Record<string, any> = options.attendance || report.attendance || {};
  const sig = (report.signatures || {}) as Record<string, any>;

  const classAverageRaw = num(report.class_average);

  return {
    lang,
    L,
    theme: buildTheme(accent),
    paper: options.paper === "A5" ? ("A5" as const) : ("A4" as const),
    school: {
      name: clean(school.name || school.school_name, "SCHOOL"),
      motto: clean(school.motto),
      logo: resolveMediaUrl(clean(school.logo || school.logo_url || school.emblem)),
      lines: [
        [school.address, school.location, school.postal_code && `P.O. Box ${school.postal_code}`].map((v) => clean(v)).filter(Boolean).join(", "),
        [school.phone, school.email].map((v) => clean(v)).filter(Boolean).join("  |  "),
        [
          school.region && `${L.region}: ${clean(school.region)}`,
          (school.division || school.department) && `${L.division}: ${clean(school.division || school.department)}`,
          (school.sub_division || school.subdivision) && `${L.subdivision}: ${clean(school.sub_division || school.subdivision)}`,
        ]
          .filter(Boolean)
          .join("  |  "),
      ].filter(Boolean),
    },
    pupil: {
      name: clean(student.name || student.full_name),
      matricule: clean(report.matricule || student.matricule || student.user?.matricule || student.admission_number),
      dob: formatDob(student.date_of_birth, lang),
      sex: (() => {
        const t = clean(student.sex || student.gender).toLowerCase();
        if (["m", "male", "masculin"].includes(t)) return L.male;
        if (["f", "female", "feminin", "féminin"].includes(t)) return L.female;
        return clean(student.sex || student.gender);
      })(),
      className: clean(report.class_name || student.class_name || student.class || student.student_class),
      section: clean(report.section || student.section),
      teacher: clean(sig.class_teacher?.name || student.class_teacher || student.class_master),
      parent: clean(sig.parent?.name || student.guardian_name),
      photo: resolveMediaUrl(clean(student.photo || student.avatar || student.user?.avatar)),
    },
    academicYear,
    termName: termLabel(L, termNumber),
    termNumber,
    maxScore,
    passMark,
    showAverage,
    show: {
      coef: showCoefficients,
      classAverage: flag(report.show_class_average),
      position: flag(report.show_subject_position),
      rank: flag(report.show_rank, flag(assessment.show_rank)),
      attendance: flag(report.show_attendance),
      conduct: flag(report.show_conduct),
      promotion: flag(report.show_promotion),
    },
    evalColumns,
    rows,
    totalCoef: num(report.total_coefficient),
    totalMarks: num(report.total_marks),
    termAverage: showAverage ? num(report.average) : null,
    averageLabel: lang === "fr" ? clean(report.average_label_fr || report.average_label) : clean(report.average_label),
    rank: num(report.rank),
    roll: num(report.total_students ?? report.enrollment),
    classAverage: classAverageRaw,
    attendance: {
      present: num(attendance.present ?? attendance.present_days ?? attendance.days_present),
      absent: num(attendance.absent ?? attendance.absent_days ?? attendance.days_absent) ?? 0,
      excused: num(attendance.excused ?? attendance.excused_days) ?? 0,
      late: num(attendance.late ?? attendance.late_coming) ?? 0,
    },
    conduct: clean(report.conduct),
    teacherComment: clean(report.teacher_comment),
    headComment: clean(report.headmaster_comment || report.principal_remark),
    decision: (report.promotion_decision as "promoted" | "repeat" | "pending" | null | undefined) || null,
    annual: hasAnnual
      ? {
          terms: [1, 2, 3].map((n) => ({ name: termLabel(L, n), value: num(termAverages[String(n)]) })),
          average: num(report.annual_average),
          label: lang === "fr" ? clean(report.annual_label_fr || report.annual_label) : clean(report.annual_label),
        }
      : null,
    signatures: {
      teacherName: clean(sig.class_teacher?.name || student.class_teacher || student.class_master),
      teacherImg: clean(sig.class_teacher?.signature),
      parentImg: clean(sig.parent?.signature),
      headName: clean(sig.headmaster?.name || school.principal),
      headImg: clean(sig.headmaster?.signature),
    },
    qrCode: clean(options.qrCode || (report as any).qr_code || (report as any).verification_qr),
    gradeBands: assessment,
    areas: (Array.isArray(report.areas) ? report.areas : [])
      .map((a: any) => ({
        name: lang === "fr" ? clean(a.name_fr || a.name) : clean(a.name || a.name_fr),
        level: num(a.level),
        order: num(a.order) ?? 0,
      }))
      .sort((a, b) => a.order - b.order),
    scale: (Array.isArray(report.nursery_scale) && report.nursery_scale.length
      ? report.nursery_scale
      : Array.isArray(assessment.nursery_scale)
        ? assessment.nursery_scale.map((s: any, i: number) => ({ level: i + 1, label: s.label, label_fr: s.label_fr }))
        : []
    ).map((s: any, i: number) => ({
      level: num(s.level) ?? i + 1,
      label: lang === "fr" ? clean(s.label_fr || s.label) : clean(s.label || s.label_fr),
    })),
  };
}

