/** HTML (style + card) for a primary or nursery report-card payload. */
export function buildBasicReportCardHtml(report: BasicReportCardPayload | Record<string, any>, options: BasicReportCardOptions = {}): string {
  const payload = (report || {}) as BasicReportCardPayload;
  const m = normalise(payload, options);
  return payload.layout === "nursery" ? buildNursery(m) : buildPrimary(m);
}

