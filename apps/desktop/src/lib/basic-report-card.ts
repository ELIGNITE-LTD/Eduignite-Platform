function gradeLegend(m: Model): string {
  const a: Record<string, any> = m.gradeBands || {};
  const out: string[] = [];
  if (a.grading_style === "descriptive" && Array.isArray(a.descriptive_bands)) {
    const bands = [...a.descriptive_bands].sort((x, y) => Number(x.min_percent) - Number(y.min_percent));
    bands.forEach((b) => {
      const from = (Number(b.min_percent) * m.maxScore) / 100;
      out.push(`${fmt(from, 1)}+: ${m.lang === "fr" ? clean(b.label_fr || b.label) : clean(b.label)}`);
    });
  } else if (Array.isArray(a.grade_bands)) {
    const bands = [...a.grade_bands].sort((x, y) => Number(x.min_score) - Number(y.min_score));
    bands.forEach((b) => out.push(`${fmt(Number(b.min_score), 1)}+: ${m.lang === "fr" ? clean(b.label_fr || b.letter) : clean(b.letter)}`));
  }
  return out.length ? `<div class="legend">${out.map((t) => `<span>${esc(t)}</span>`).join("")}</div>` : `<div style="height:.8em"></div>`;
}

function buildPrimary(m: Model): string {
  const L = m.L;
  const compact = m.rows.length > 13;
  const hasClassAvg = m.showAverage && m.show.classAverage && m.rows.some((r) => r.classAverage !== null);
  const hasPos = m.show.position && m.rows.some((r) => r.position !== null);
  const marks = m.showAverage;

  // Column plan
  const heads: string[] = [`<th class="l" style="width:auto">${esc(L.subject)}</th>`];
  m.evalColumns.forEach((c) => heads.push(`<th style="width:5.2em">${esc(c.label)}<small>(/${esc(fmt(m.maxScore))})</small></th>`));
  if (marks) heads.push(`<th style="width:5.6em">${esc(L.average)}<small>(/${esc(fmt(m.maxScore))})</small></th>`);
  if (marks && m.show.coef) {
    heads.push(`<th style="width:3.8em">${esc(L.coef)}</th>`);
    heads.push(`<th style="width:5.4em">${esc(L.coefAvg)}</th>`);
  }
  if (hasClassAvg) heads.push(`<th style="width:5.4em">${esc(L.classAvg)}</th>`);
  if (hasPos) heads.push(`<th style="width:3.6em">${esc(L.position)}</th>`);
  heads.push(`<th style="width:${marks ? 9 : 14}em">${esc(L.remark)}</th>`);
  const colCount = heads.length;

  const body = m.rows.length
    ? m.rows
        .map((r) => {
          const bad = r.average !== null && r.average < m.passMark;
          const cells: string[] = [`<td class="l">${esc(r.name)}</td>`];
          r.evals.forEach((v) => cells.push(`<td class="m">${esc(fmt(v))}</td>`));
          if (marks) cells.push(`<td class="g">${esc(fmt2(r.average))}</td>`);
          if (marks && m.show.coef) cells.push(`<td>${esc(fmt(r.coef))}</td><td class="g">${esc(fmt2(r.coefAverage))}</td>`);
          if (hasClassAvg) cells.push(`<td class="m">${esc(fmt2(r.classAverage))}</td>`);
          if (hasPos) cells.push(`<td>${r.position ? esc(ordinal(r.position, m.lang)) : "-"}</td>`);
          cells.push(`<td class="${r.average === null && marks ? "m" : bad ? "ko" : "ok"}" style="text-align:left;padding-left:.5em">${esc(r.label || "-")}</td>`);
          return `<tr>${cells.join("")}</tr>`;
        })
        .join("")
    : `<tr><td class="empty" colspan="${colCount}">${esc(L.noMarks)}</td></tr>`;

  // Totals row
  let totals = "";
  if (marks && m.rows.length) {
    const lead = 1 + m.evalColumns.length + 1; // subject + evals + average
    const parts: string[] = [];
    if (m.show.coef) {
      parts.push(`<td class="r" colspan="${lead}">${esc(L.total)}:</td><td>${esc(fmt(m.totalCoef))}</td><td>${esc(fmt2(m.totalMarks))}</td>`);
      const rest = colCount - lead - 2;
      if (rest > 0) parts.push(`<td colspan="${rest}"></td>`);
    } else {
      parts.push(`<td class="r" colspan="${lead}">${esc(L.total)}: ${esc(fmt2(m.totalMarks))}</td>`);
      const rest = colCount - lead;
      if (rest > 0) parts.push(`<td colspan="${rest}"></td>`);
    }
    totals = `<tr class="tot">${parts.join("")}</tr>`;
  }

  // Summary boxes
  const boxes: string[] = [];
  if (marks) {
    const ok = m.termAverage !== null && m.termAverage >= m.passMark;
    const pill =
      m.termAverage === null ? "" : `<span class="pill ${ok ? "ok" : "ko"}">${esc(ok ? L.passed : L.failed)}</span>`;
    boxes.push(`
      <div class="card">
        <h5>${esc(L.termAverage)}</h5>
        <div class="big">${m.termAverage !== null ? `${esc(fmt2(m.termAverage))} / ${esc(fmt(m.maxScore))}` : "-"}</div>
        <div class="sub"><span>${esc(m.averageLabel)}</span>${pill}</div>
      </div>`);
  } else if (m.averageLabel) {
    boxes.push(`<div class="card"><h5>${esc(L.termAverage)}</h5><div class="mid">${esc(m.averageLabel)}</div></div>`);
  }
  const showRank = marks && m.show.rank;
  const showClassAvg = marks && m.show.classAverage && m.classAverage !== null;
  if (showRank || showClassAvg) {
    boxes.push(`
      <div class="card">
        ${
          showRank
            ? `<h5>${esc(L.rank)}</h5><div class="mid">${m.rank !== null ? `${esc(ordinal(m.rank, m.lang))} ${esc(L.outOf)} ${esc(m.roll ?? "-")}` : "-"}</div>`
            : `<h5>${esc(L.roll)}</h5><div class="mid">${esc(m.roll ?? "-")}</div>`
        }
        ${showClassAvg ? `<div class="kv"><span>${esc(L.classAverage)}</span><b>${esc(fmt2(m.classAverage))}</b></div>` : ""}
      </div>`);
  }
  if (m.show.attendance || m.show.conduct) {
    const a = m.attendance;
    const rows: string[] = [];
    if (m.show.attendance) {
      rows.push(`<div class="kv"><span>${esc(L.absences)}</span><b>${esc(a.absent)}${a.excused ? ` (${esc(L.excused)}: ${esc(a.excused)})` : ""}</b></div>`);
      rows.push(`<div class="kv"><span>${esc(L.late)}</span><b>${esc(a.late)}</b></div>`);
    }
    if (m.show.conduct) rows.push(`<div class="kv"><span>${esc(L.conduct)}</span><b>${esc(m.conduct || "-")}</b></div>`);
    boxes.push(`<div class="card"><h5>${esc(m.show.attendance ? L.attendance : L.conduct)}</h5>${rows.join("")}</div>`);
  }

  // Annual summary + decision (final term)
  let annual = "";
  if (m.annual && (marks || (m.show.promotion && m.decision))) {
    const decisionOn = m.show.promotion && m.decision;
    const cells = !marks ? [] : [
      ...m.annual.terms.map((t) => `<div class="c"><small>${esc(t.name)}</small><b>${esc(fmt2(t.value))}</b></div>`),
      `<div class="c hi"><small>${esc(L.annualAverage)}</small><b>${esc(fmt2(m.annual.average))}</b>${m.annual.label ? `<div style="font-size:.7em;font-weight:700;color:#64748b">${esc(m.annual.label)}</div>` : ""}</div>`,
    ];
    const dec = decisionOn
      ? (() => {
          const label = m.decision === "promoted" ? L.promoted : m.decision === "repeat" ? L.repeat : L.pending;
          const cls = m.decision === "promoted" ? "ok" : m.decision === "repeat" ? "ko" : "mu";
          return `<div class="dec c"><small>${esc(L.decision)}</small><b class="${cls === "mu" ? "" : cls}" style="${cls === "mu" ? "color:#64748b" : ""}">${esc(label)}</b></div>`;
        })()
      : "";
    annual = `<div class="annual"><div class="tt">${esc(L.annualSummary)}</div>${cells.join("")}${dec}</div>`;
  }

  return `${styles(m, compact)}
    <section class="rc bx bx-primary" data-layout="primary">
      ${header(m, L.reportTitle, L.reportSub)}
      ${chips(m)}
      ${pupilBlock(m, [L.roll, m.roll !== null ? String(m.roll) : ""], compact)}
      <table class="t"><thead><tr>${heads.join("")}</tr></thead><tbody>${body}${totals}</tbody></table>
      ${marks ? gradeLegend(m) : '<div style="height:.8em"></div>'}
      ${boxes.length ? `<div class="boxes">${boxes.join("")}</div>` : ""}
      ${annual}
      ${remarks(m, L.teacherRemark)}
      ${signatures(m)}
      ${footer(m)}
    </section>`;
}

